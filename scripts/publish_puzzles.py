#!/usr/bin/env python3
"""Publish the puzzle files in puzzles/ to Supabase.

Runs scripts/check_puzzles.py first and refuses to publish if anything fails.
By default only today and later are sent (with a day of slack for time zones), so a
puzzle people have already played never changes under them. Rows are upserted on
(number, format), so re-running is safe and edits to upcoming puzzles go through.

Usage:
  SUPABASE_URL=... SUPABASE_SERVICE_ROLE_KEY=... python3 scripts/publish_puzzles.py
  python3 scripts/publish_puzzles.py --dry-run           # show what would be sent
  python3 scripts/publish_puzzles.py --all               # include past days too
  python3 scripts/publish_puzzles.py --sql > supabase/seed.sql   # every puzzle as SQL, for the SQL editor
The service role key bypasses row-level security: keep it in CI secrets, never in the app.
Standard library only.
"""
import argparse
import datetime as dt
import json
import os
import sys
import urllib.error
import urllib.request
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import check_puzzles as C  # noqa: E402


def to_row(p):
    """One puzzle file entry -> one row of public.puzzles (see supabase/schema.sql)."""
    date = dt.date.fromisoformat(p['date'])
    if p['format'] == 'order':
        solution, hint = p['solution'], None
    elif p['format'] == 'bug':
        solution, hint = {'bug': p['bug'], 'fix': p['fix']}, p['hint']
    else:
        solution, hint = {'choices': p['choices'], 'answer': p['answer']}, p.get('hint')
    return {
        'number': C.puzzle_number(date),
        'publish_date': p['date'],
        'format': p['format'],
        'title': p['title'],
        'prompt': p['prompt'],
        'lines': p['lines'],  # tests stay in the repo; the app never needs them
        'solution': solution,
        'hint': hint,
        'why': p['why'],
    }


def all_rows():
    rows = []
    for path in sorted(C.PUZZLE_DIR.glob('*.json')):
        rows += [to_row(p) for p in json.loads(path.read_text(encoding='utf-8'))['puzzles']]
    return sorted(rows, key=lambda r: (r['publish_date'], C.FORMATS.index(r['format'])))


def sql(rows):
    q = lambda v: 'null' if v is None else "'" + str(v).replace("'", "''") + "'"
    j = lambda v: q(json.dumps(v, ensure_ascii=False, separators=(',', ':'))) + '::jsonb'
    values = ',\n'.join(
        f"  ({r['number']}, '{r['publish_date']}', '{r['format']}', {q(r['title'])}, {q(r['prompt'])}, "
        f"{j(r['lines'])}, {j(r['solution'])}, {q(r['hint'])}, {q(r['why'])})"
        for r in rows
    )
    return (
        '-- Generated by scripts/publish_puzzles.py --sql from puzzles/*.json. Do not edit by hand.\n'
        '-- Paste into the Supabase SQL editor after schema.sql. Safe to re-run.\n'
        'insert into public.puzzles (number, publish_date, format, title, prompt, lines, solution, hint, why) values\n'
        f'{values}\n'
        'on conflict (number, format) do nothing;\n'
    )


def upsert(rows, url, key):
    req = urllib.request.Request(
        url.rstrip('/') + '/rest/v1/puzzles?on_conflict=number,format',
        data=json.dumps(rows).encode(),
        method='POST',
        headers={
            'apikey': key,
            'Authorization': f'Bearer {key}',
            'Content-Type': 'application/json',
            'Prefer': 'resolution=merge-duplicates,return=minimal',
        },
    )
    try:
        with urllib.request.urlopen(req, timeout=30) as res:
            return res.status
    except urllib.error.HTTPError as e:
        sys.exit(f'Supabase rejected the upload ({e.code}): {e.read().decode(errors="replace")}')
    except urllib.error.URLError as e:
        sys.exit(f'Could not reach Supabase: {e.reason}')


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument('--dry-run', action='store_true', help='print what would be sent and stop')
    mode.add_argument('--sql', action='store_true', help='print every puzzle as a SQL insert and stop')
    ap.add_argument('--all', action='store_true', help='also send days that have already passed')
    args = ap.parse_args(argv)

    # Checker output goes to stderr so --sql output stays clean.
    stdout, sys.stdout = sys.stdout, sys.stderr
    try:
        failed = C.main([])
    finally:
        sys.stdout = stdout
    if failed:
        sys.exit('Not publishing: fix the problems above first.')

    rows = all_rows()
    if args.sql:
        sys.stdout.write(sql(rows))
        return 0

    cutoff = (dt.datetime.now(dt.timezone.utc).date() - dt.timedelta(days=1)).isoformat()
    if not args.all:
        rows = [r for r in rows if r['publish_date'] >= cutoff]
    if not rows:
        print('Nothing to publish: every puzzle is in the past. Add next week\'s file.')
        return 0
    first, last = rows[0]['publish_date'], rows[-1]['publish_date']
    print(f'{len(rows)} puzzle(s) from {first} to {last}' + ('' if args.all else f' (skipping days before {cutoff})'))

    if args.dry_run:
        for r in rows:
            print(f"  No. {r['number']:>3}  {r['publish_date']}  {r['format']:<6}  {r['title']}")
        return 0

    url, key = os.environ.get('SUPABASE_URL'), os.environ.get('SUPABASE_SERVICE_ROLE_KEY')
    if not url or not key:
        sys.exit('Set SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY (Supabase: Project Settings > API).')
    status = upsert(rows, url, key)
    print(f'Published (HTTP {status}).')
    return 0


if __name__ == '__main__':
    sys.exit(main())
